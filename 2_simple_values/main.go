package main

import "fmt"

func main() {
	//simple values
	fmt.Println("Learning Go is fun!")

	//integer values
	var a int = 10
	fmt.Println("Value of a:", a)
	fmt.Println(1)
	fmt.Println(1 + 1)

	//float values
	var b float64 = 3.14
	fmt.Println("Value of b:", b)
	fmt.Println(3.14)
	fmt.Println(7.0 / 2.0)
	fmt.Println(3.14 * 3.14)

	//string values
	var c string = "Hello, Go!"
	fmt.Println("Value of c:", c)

	//boolean values
	var d bool = true
	fmt.Println("Value of d:", d)
}
